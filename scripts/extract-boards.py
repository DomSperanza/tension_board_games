#!/usr/bin/env python3
"""Regenerate src/js/boards-data.js from the Tension and Kilter app databases.

Get the databases with BoardLib (https://github.com/lemeryfertitta/BoardLib):
    pip install boardlib
    boardlib database tension tension.db
    boardlib database kilter kilter.db

Usage: python3 scripts/extract-boards.py path/to/tension.db path/to/kilter.db
"""
import sqlite3
import sys
from pathlib import Path

# Per brand: product id -> (family, kickboard top) and product size id -> name shown in the board picker.
# Holes below the kickboard top sit on the kickboard.
#   Tension TB1: rows KB1 / KB2 are at y = 4 / 8, row 1 starts at y = 16. TB2 has no kickboard in the app.
#   Kilter Original: product size "without kickboard" starts at 12. Homewall: the kickboard sets are at y = -4 / -8.
# The apps' own size names are inconsistent, so these are written out by hand.
BRANDS = {
    'tension': {
        'products': {5: ('tb2', None), 4: ('tb1', 12)},
        'names': {
            6: 'TB2 12×12',
            7: 'TB2 12×10',
            8: 'TB2 8×12',
            9: 'TB2 8×10',
            10: 'TB2 16×12',
            1: 'TB1 Full Wall (KB1 + KB2)',
            2: 'TB1 Half Kickboard (KB2)',
            3: 'TB1 No Kickboard',
            4: 'TB1 Short',
            5: 'TB1 Short & Narrow',
        },
    },
    'kilter': {
        'products': {1: ('kilter-original', 12), 7: ('kilter-homewall', 0)},
        'names': {
            10: 'Original 12×12 with kickboard',
            27: 'Original 12×12 no kickboard',
            7: 'Original 12×14 Commercial',
            28: 'Original 16×12 Super Wide',
            8: 'Original 8×12 Home',
            14: 'Original 7×10 Small',
            17: 'Homewall 7×10 Full Ride',
            18: 'Homewall 7×10 Mainline',
            19: 'Homewall 7×10 Auxiliary',
            21: 'Homewall 10×10 Full Ride',
            22: 'Homewall 10×10 Mainline',
            29: 'Homewall 10×10 Auxiliary',
            23: 'Homewall 8×12 Full Ride',
            24: 'Homewall 8×12 Mainline',
            25: 'Homewall 10×12 Full Ride',
            26: 'Homewall 10×12 Mainline',
        },
    },
}
PER_LINE = 20


def boards(brand, db_path):
    db = sqlite3.connect(db_path)
    config = BRANDS[brand]
    out = []
    for size_id, name in config['names'].items():
        (product_id,) = db.execute('SELECT product_id FROM product_sizes WHERE id = ?', (size_id,)).fetchone()
        leds = db.execute(
            'SELECT l.position, h.x, h.y FROM leds l JOIN holes h ON h.id = l.hole_id '
            'WHERE l.product_size_id = ? ORDER BY l.position',
            (size_id,),
        ).fetchall()
        family, top = config['products'][product_id]
        kickboard = top if top is not None and any(y < top for _, _, y in leds) else None
        out.append(
            f"  {{ id: '{brand}-{size_id}', brand: '{brand}', family: '{family}', name: '{name}', "
            f"kickboardTop: {'null' if kickboard is None else kickboard}, leds: ["
        )
        cells = [f'[{p},{x},{y}]' for p, x, y in leds]
        for i in range(0, len(cells), PER_LINE):
            out.append('    ' + ','.join(cells[i : i + PER_LINE]) + ',')
        out.append('  ] },')
    return out


def main(tension_db, kilter_db):
    out = [
        '// Generated by scripts/extract-boards.py from the Tension and Kilter app databases. Do not edit by hand.',
        '// leds: [ledPosition, holeX, holeY] in board units (inches, y up). kickboardTop: holes below are on the kickboard.',
        'export const BOARDS = [',
        *boards('tension', tension_db),
        *boards('kilter', kilter_db),
        '];',
    ]
    target = Path(__file__).resolve().parent.parent / 'src' / 'js' / 'boards-data.js'
    target.write_text('\n'.join(out) + '\n')
    count = sum(len(b['names']) for b in BRANDS.values())
    print(f'Wrote {target} ({count} boards)')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
