#!/usr/bin/env python3
"""Regenerate src/js/boards-data.js from the Tension Board app database.

Get the database with BoardLib (https://github.com/lemeryfertitta/BoardLib):
    pip install boardlib pillow
    boardlib database tension tension.db

Usage: python3 scripts/extract-boards.py path/to/tension.db
"""
import sqlite3
import sys
from pathlib import Path

TB1, TB2 = 4, 5
# Holes below this height sit on the kickboard. TB1: rows KB1 / KB2 are at y = 4 / 8, row 1 starts at y = 16.
# TB2 has no kickboard in the app.
KICKBOARD_TOP = {TB1: 12, TB2: None}
# Product size id -> name shown in the board picker. TB2 sizes are width × height in feet.
NAMES = {
    6: 'TB2 12×12',
    7: 'TB2 12×10',
    8: 'TB2 8×12',
    9: 'TB2 8×10',
    10: 'TB2 16×12',
    1: 'TB1 Full Wall (KB1 + KB2)',
    2: 'TB1 Half Kickboard (KB2)',
    3: 'TB1 No Kickboard',
    4: 'TB1 Short',
    5: 'TB1 Short & Narrow',
}
PER_LINE = 20


def main(db_path):
    db = sqlite3.connect(db_path)
    out = [
        '// Generated by scripts/extract-boards.py from the Tension Board app database. Do not edit by hand.',
        '// leds: [ledPosition, holeX, holeY] in board units (inches, y up). kickboardTop: holes below are on the kickboard.',
        'export const BOARDS = [',
    ]
    for size_id, name in NAMES.items():
        (product_id,) = db.execute('SELECT product_id FROM product_sizes WHERE id = ?', (size_id,)).fetchone()
        leds = db.execute(
            'SELECT l.position, h.x, h.y FROM leds l JOIN holes h ON h.id = l.hole_id '
            'WHERE l.product_size_id = ? ORDER BY l.position',
            (size_id,),
        ).fetchall()
        top = KICKBOARD_TOP[product_id]
        kickboard = top if top is not None and any(y < top for _, _, y in leds) else None
        family = 'tb1' if product_id == TB1 else 'tb2'
        out.append(f"  {{ id: {size_id}, family: '{family}', name: '{name}', kickboardTop: {'null' if kickboard is None else kickboard}, leds: [")
        cells = [f'[{p},{x},{y}]' for p, x, y in leds]
        for i in range(0, len(cells), PER_LINE):
            out.append('    ' + ','.join(cells[i : i + PER_LINE]) + ',')
        out.append('  ] },')
    out.append('];')
    target = Path(__file__).resolve().parent.parent / 'src' / 'js' / 'boards-data.js'
    target.write_text('\n'.join(out) + '\n')
    print(f'Wrote {target} ({len(NAMES)} boards)')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
